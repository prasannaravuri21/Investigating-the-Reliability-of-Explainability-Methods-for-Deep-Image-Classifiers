"""Week 8: wire this project's attribution methods into the FunnyBirds framework.

The framework is run from its own clone, not from here. This script does the two
things that are fiddly about that: it writes the bridging file their
`evaluate_explainability.py` imports, and it prints the exact commands with the
right flags.

    python scripts/w8_funnybirds.py --framework D:\\code\\funnybirds-framework ^
        --checkpoint-dir D:\\data\\funnybirds_ckpt

Afterwards, run the printed commands inside the framework clone. Results land in
its own output files; copy the headline numbers into
results/scores_funnybirds.csv using the column names this project already uses
(model, method, metric, seed, score) so scripts/w9_analysis.py picks them up as
a third metric with no code change.
"""
import argparse
from pathlib import Path

import _bootstrap  # noqa: F401
from src.utils import get_logger

LOG = get_logger()

BRIDGE = '''"""Auto-generated by scripts/w8_funnybirds.py -- do not edit by hand.

Exposes this project's attribution methods to the FunnyBirds framework. Drop
this file in the framework's `explainers/` folder and add the branch printed by
that script to `evaluate_explainability.py`.
"""
import sys

# The reliability project, so the SAME attribution code is scored here as is
# scored by ROAD and IDSDS. If these diverged, the comparison would be void.
PROJECT_ROOT = r"{project_root}"
if PROJECT_ROOT not in sys.path:
    sys.path.insert(0, PROJECT_ROOT)

from src.config import load_config                       # noqa: E402
from src.funnybirds import FunnyBirdsExplainer            # noqa: E402
from src.models import ModelWrapper, _torchvision_normalise, _vit_reshape  # noqa: E402

_CFG = load_config(r"{config_path}")

_LAYERS = {{
    "resnet50": ("layer4.-1", None, True),
    "vgg16": ("features.-1", None, True),
    "vit_b_16": ("encoder.layers.-1.ln_1", _vit_reshape, False),
}}


def build_explainer(model, arch, method, device="cuda"):
    \"\"\"Wrap the framework's own model object and return our explainer.

    The framework has already built and loaded the model, so it is reused here
    rather than loaded again -- that way the explanation is definitely of the
    model being evaluated.
    \"\"\"
    layer, reshape, lrp_ok = _LAYERS[arch]
    inner = getattr(model, "model", model)   # unwrap their modelwrapper if present
    wrapper = ModelWrapper(
        name=f"funnybirds_{{arch}}",
        model=inner,
        normalise=_torchvision_normalise(),
        gradcam_layer=layer,
        gradcam_reshape=reshape,
        lrp_supported=lrp_ok,
        image_size=256,
        notes="wrapped FunnyBirds framework model",
    ).to(device)
    return FunnyBirdsExplainer(wrapper, method, _CFG)


class CustomExplainer(FunnyBirdsExplainer):
    \"\"\"Entry point the framework instantiates. Set METHOD before use, or pass
    it through the framework's --explainer argument parsing.\"\"\"

    METHOD = "gradcam"

    def __init__(self, model, arch="resnet50", method=None, device="cuda", **kwargs):
        built = build_explainer(model, arch, method or self.METHOD, device)
        super().__init__(built.wrapper, built.method, built.cfg)
'''

BRANCH = '''    elif args.explainer == 'CustomExplainer':
        from explainers.reliability_bridge import CustomExplainer
        explainer = CustomExplainer(model, arch=args.model,
                                    method=args.custom_method, device=device)'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--framework", required=True, help="path to your funnybirds-framework clone")
    ap.add_argument("--checkpoint-dir", default="<checkpoints>", help="where the .pth checkpoints live")
    ap.add_argument("--config", default=None)
    ap.add_argument("--models", nargs="*", default=["resnet50", "vit_b_16"])
    ap.add_argument("--methods", nargs="*",
                    default=["gradcam", "integrated_gradients", "lrp", "rise", "gradient_shap"])
    args = ap.parse_args()

    framework = Path(args.framework)
    explainers = framework / "explainers"
    if not explainers.exists():
        raise SystemExit(
            f"{explainers} not found. Clone the framework first:\n"
            "  git clone https://github.com/visinf/funnybirds-framework"
        )

    project_root = Path(__file__).resolve().parents[1]
    config_path = Path(args.config) if args.config else project_root / "configs" / "default.yaml"
    bridge_path = explainers / "reliability_bridge.py"
    bridge_path.write_text(
        BRIDGE.format(project_root=str(project_root), config_path=str(config_path)),
        encoding="utf-8",
    )
    LOG.info("wrote %s", bridge_path)

    print("\n1. Add this branch to evaluate_explainability.py, next to the other")
    print("   `elif args.explainer == ...` cases, and add a --custom_method argument:\n")
    print(BRANCH)
    print("\n2. Run the protocol. LRP on the ViT will refuse, as it does elsewhere:\n")
    for model in args.models:
        for method in args.methods:
            if model == "vit_b_16" and method == "lrp":
                print(f"   # skipped: lrp on {model} (no settled attention rule)")
                continue
            print(f"   python evaluate_explainability.py --model {model} \\")
            print(f"       --checkpoint_name {args.checkpoint_dir}/{model}.pth \\")
            print(f"       --explainer CustomExplainer --custom_method {method} \\")
            print(f"       --accuracy --controlled_synthetic_data_check --single_deletion \\")
            print(f"       --preservation_check --deletion_check --target_sensitivity \\")
            print(f"       --distractibility --background_independence\n")

    print("3. Copy the headline numbers into results/scores_funnybirds.csv with columns")
    print("   model,method,metric,seed,score  (metric=funnybirds_<metricname>), then run")
    print("   python scripts/w9_analysis.py")
    print("\nNote: their single_deletion metric is the closest relative of IDSDS, from the")
    print("same authors, so it is the most directly comparable of the FunnyBirds numbers.")


if __name__ == "__main__":
    main()
